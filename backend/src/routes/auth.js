// PATCH /api/auth/me  — self-service profile update (role-aware)
// Updates User collection for all roles.
// Also syncs to Tutor doc (tutor role) or Student doc (student role).
router.patch('/me', protect, async (req, res) => {
  try {
    const { role, _id: userId, linkedId } = req.user;

    // ── 1. User collection ────────────────────────────────────────────────────
    const USER_FIELDS = [
      'firstName', 'lastName', 'displayName',
      'phone', 'dialCode', 'countryCode',
      'dob', 'gender', 'profileImage',
    ];
    const userUpdate = {};
    USER_FIELDS.forEach((f) => { if (req.body[f] !== undefined) userUpdate[f] = req.body[f]; });

    // Recompute `name` when first/last changes (findByIdAndUpdate skips pre-save hook)
    if (userUpdate.firstName !== undefined || userUpdate.lastName !== undefined) {
      const cur = await User.findById(userId).select('firstName lastName');
      const fn = userUpdate.firstName ?? cur.firstName;
      const ln = userUpdate.lastName  ?? (cur.lastName || '');
      userUpdate.name = [fn, ln].filter(Boolean).join(' ');
    }

    const updatedUser = await User.findByIdAndUpdate(
      userId, userUpdate, { new: true, runValidators: true },
    );
    if (!updatedUser) return res.status(404).json({ success: false, message: 'User not found' });

    // ── 2. Tutor doc sync ─────────────────────────────────────────────────────
    if (role === 'tutor' && linkedId) {
      const TUTOR_FIELDS = ['qualification', 'experience', 'subjects', 'phone', 'profileImage'];
      const tutorUpdate = {};
      TUTOR_FIELDS.forEach((f) => { if (req.body[f] !== undefined) tutorUpdate[f] = req.body[f]; });
      if (userUpdate.name) tutorUpdate.name = userUpdate.name;
      if (Object.keys(tutorUpdate).length > 0) {
        await Tutor.findByIdAndUpdate(linkedId, tutorUpdate);
      }
    }

    // ── 3. Student doc sync ───────────────────────────────────────────────────
    if (role === 'student' && linkedId) {
      const STUDENT_FIELDS = [
        'grade', 'subjects', 'parentName', 'parentEmail', 'parentPhone',
        'phone', 'profileImage',
      ];
      const studentUpdate = {};
      STUDENT_FIELDS.forEach((f) => { if (req.body[f] !== undefined) studentUpdate[f] = req.body[f]; });
      if (userUpdate.name) studentUpdate.name = userUpdate.name;
      if (Object.keys(studentUpdate).length > 0) {
        await Student.findByIdAndUpdate(linkedId, studentUpdate);
      }
    }

    res.json({ success: true, user: updatedUser.toJSON() });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
});

// PATCH /api/auth/me/change-password
router.patch('/me/change-password', protect, async (req, res) => {
  try {
    const { currentPassword, newPassword } = req.body;
    if (!currentPassword || !newPassword) {
      return res.status(400).json({ success: false, message: 'currentPassword and newPassword are required' });
    }
    if (newPassword.length < 6) {
      return res.status(400).json({ success: false, message: 'Password must be at least 6 characters' });
    }
    const user = await User.findById(req.user._id).select('+password');
    if (!user) return res.status(404).json({ success: false, message: 'User not found' });
    const ok = await user.comparePassword(currentPassword);
    if (!ok) return res.status(401).json({ success: false, message: 'Current password is incorrect' });
    user.password = newPassword;
    await user.save();
    res.json({ success: true, message: 'Password updated successfully' });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
});

